//! Compact stroke font for TEXT / MTEXT (ASCII). Coordinates are 0..1.

use cad_core::Point2;

pub fn measure_width(text: &str, height: f64) -> f64 {
    text.chars().count() as f64 * height * 0.8
}

pub fn stroke_text(origin: Point2, height: f64, rotation: f64, text: &str) -> Vec<[Point2; 2]> {
    let mut segments = Vec::new();
    let c = rotation.cos();
    let s = rotation.sin();
    let mut x_cursor = 0.0;
    let advance = height * 0.8;
    let cell = height * 0.7;
    for ch in text.chars() {
        if ch == '\n' {
            x_cursor = 0.0;
            continue;
        }
        for [a, b] in glyph(ch) {
            let p0 = Point2::new(a.x * cell + x_cursor, a.y * cell);
            let p1 = Point2::new(b.x * cell + x_cursor, b.y * cell);
            let w0 = Point2::new(
                origin.x + p0.x * c - p0.y * s,
                origin.y + p0.x * s + p0.y * c,
            );
            let w1 = Point2::new(
                origin.x + p1.x * c - p1.y * s,
                origin.y + p1.x * s + p1.y * c,
            );
            segments.push([w0, w1]);
        }
        x_cursor += advance;
    }
    segments
}

pub fn strip_mtext(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    let chars: Vec<char> = raw.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        match chars[i] {
            '\\' if i + 1 < chars.len() => match chars[i + 1] {
                'P' | 'p' | 'X' | 'x' => {
                    out.push('\n');
                    i += 2;
                }
                '~' => {
                    out.push(' ');
                    i += 2;
                }
                '\\' => {
                    out.push('\\');
                    i += 2;
                }
                '{' | '}' => {
                    out.push(chars[i + 1]);
                    i += 2;
                }
                'A' | 'C' | 'F' | 'H' | 'Q' | 'T' | 'W' | 'f' | 'c' | 'h' => {
                    i += 2;
                    while i < chars.len() && chars[i] != ';' {
                        i += 1;
                    }
                    if i < chars.len() {
                        i += 1;
                    }
                }
                _ => {
                    i += 1;
                }
            },
            '{' | '}' => i += 1,
            ch => {
                out.push(ch);
                i += 1;
            }
        }
    }
    out
}

